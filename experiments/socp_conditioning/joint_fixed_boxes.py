def variable_schema(variables):
    """Ignore only autogenerated auxiliary names, retaining order and shape."""
    result = []
    auxiliary = 0
    for v in sorted(variables, key=lambda v: v["offset"]):
        name = v["name"]
        if name.startswith("var") and name[3:].isdigit():
            name = f"auxiliary_{auxiliary}"
            auxiliary += 1
        result.append((name, tuple(v["shape"]), v["offset"]))
    return result


def check_cleanup(old, new, variables):
    """Prove the only canonical change is selected opposite boxes to equality.

    Objective and cone rows are exact, not sampled feasible points. Equality
    and nonnegative rows are compared as multisets because CVXPY regroups rows.
    Only exact unary coincident bounds on Pg and p_nd can be removed.
    """
    np.testing.assert_array_equal(old["c"], new["c"])
    if (old["P"] != new["P"]).nnz:
        raise ValueError("quadratic objective changed")
    lo, ln = (oa.cone_layout(str(p["dims"]), p["A"].shape[0]) for p in (old, new))
    if lo[2] != ln[2]:
        raise ValueError("SOC layout changed")
    A, B = old["A"].tocsr(), new["A"].tocsr()
    A.sum_duplicates()
    B.sum_duplicates()
    A.eliminate_zeros()
    B.eliminate_zeros()

    def row(matrix, rhs, k):
        start, stop = matrix.indptr[k : k + 2]
        return (
            tuple(matrix.indices[start:stop]),
            tuple(matrix.data[start:stop]),
            float(rhs[k]),
        )

    bounds = {}
    allowed = {
        int(i) for v in variables if v["name"] in ("Pg", "p_nd") for i in oa.indices(v)
    }
    for k in range(lo[0], sum(lo[:2])):
        ii, vv, rhs = row(A, old["b"], k)
        if len(ii) == 1 and ii[0] in allowed:
            bounds.setdefault(ii[0], []).append((k, vv[0], rhs / vv[0]))
    removed, inserted = set(), []
    for col, entries in bounds.items():
        pairs = [
            (a, b) for a in entries for b in entries if a[1] < 0 < b[1] and a[2] == b[2]
        ]
        if len(pairs) > 1:
            raise ValueError("ambiguous coincident bounds")
        if pairs:
            a, b = pairs[0]
            removed.update((a[0], b[0]))
            inserted.append(((col,), (1.0,), float(a[2])))
    if ln[:2] != (lo[0] + len(inserted), lo[1] - len(removed)):
        raise ValueError("unexpected equality/inequality counts")
    expected_eq = Counter(row(A, old["b"], k) for k in range(lo[0])) + Counter(inserted)
    actual_eq = Counter(row(B, new["b"], k) for k in range(ln[0]))
    expected_ineq = Counter(
        row(A, old["b"], k) for k in range(lo[0], sum(lo[:2])) if k not in removed
    )
    actual_ineq = Counter(row(B, new["b"], k) for k in range(ln[0], sum(ln[:2])))
    if expected_eq != actual_eq or expected_ineq != actual_ineq:
        raise ValueError("non-box rows or fixed values changed")
    if (A[sum(lo[:2]) :] != B[sum(ln[:2]) :]).nnz:
        raise ValueError("cone coefficients changed")
    np.testing.assert_array_equal(old["b"][sum(lo[:2]) :], new["b"][sum(ln[:2]) :])
    return dict(
        fixed_coordinates=len(inserted),
        removed_inequalities=len(removed),
        old_equalities=lo[0],
        new_equalities=ln[0],
        old_inequalities=lo[1],
        new_inequalities=ln[1],
        exact_canonical_cleanup_verified=True,
    )


def worker(directory, reference, label):
    case, prior = ARMS[label]

    def verify(data, inverse, input_hash, fixed):
        folder = d.HERE / "results" / prior
        old = m.verified_record(folder)
        if old["input_sha256"] != input_hash:
            raise ValueError("historical physical inputs differ")
        if d.sha(folder / "canonical.npz") != old["canonical_archive"]["sha256"]:
            raise ValueError("historical canonical hash mismatch")
        current_vars = [
            dict(name=v.name(), shape=v.shape, offset=inverse[-2].var_offsets[v.id])
            for v in data["param_prob"].variables
        ]
        variables = old["canonical_archive"]["variables"]
        if variable_schema(current_vars) != variable_schema(variables):
            raise ValueError("canonical variable identity/order changed")
        if (
            float(inverse[-1]["offset"])
            != old["canonical_evidence"]["canonical_offset"]
        ):
            raise ValueError("objective constant changed")
        source = ca.matrices(folder / "canonical.npz")
        source["dims"] = old["canonical_archive"]["cone_dimensions"]
        return check_cleanup(source, data, variables) | dict(
            directory=str(folder),
            arm_sha256=d.sha(folder / "arm.json.gz"),
            canonical_sha256=d.sha(folder / "canonical.npz"),
        )

    BASE_WORKER(
        directory,
        reference,
        label,
        scaling_strategy=j.joint_scales,
        case_name=case,
        reference_validator=verify,
        model_variant="fixed_boxes",
    )


if __name__ == "__main__":
    with (
        patch.object(c, "context", context),
        patch.object(c, "ARMS", tuple(ARMS)),
        patch.object(c, "worker", worker),
    ):
        c.main(worker_module=__spec__.name)
